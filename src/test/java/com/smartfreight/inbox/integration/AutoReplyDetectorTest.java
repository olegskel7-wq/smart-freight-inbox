package com.smartfreight.inbox.integration;

import jakarta.mail.Session;
import jakarta.mail.internet.MimeMessage;
import org.junit.jupiter.api.Test;

import java.util.Properties;

import static org.assertj.core.api.Assertions.assertThat;

/** Header rules of {@link AutoReplyDetector}: which messages are automatic replies and which are not. */
class AutoReplyDetectorTest {

    private static MimeMessage message(String... headerPairs) throws Exception {
        MimeMessage msg = new MimeMessage(Session.getInstance(new Properties()));
        msg.setSubject("Automatic reply: your enquiry");
        msg.setText("I am out of the office.");
        for (int i = 0; i < headerPairs.length; i += 2) {
            msg.setHeader(headerPairs[i], headerPairs[i + 1]);
        }
        return msg;
    }

    @Test
    void plainMessage_isNotAnAutoReply() throws Exception {
        // Subject and body look like an out-of-office note; without the headers it is still mail to read.
        assertThat(AutoReplyDetector.isAutoReply(message())).isFalse();
    }

    @Test
    void autoSubmittedAutoReplied_isAnAutoReply() throws Exception {
        assertThat(AutoReplyDetector.isAutoReply(message("Auto-Submitted", "auto-replied"))).isTrue();
        // Header values are case-insensitive and may carry parameters (RFC 3834).
        assertThat(AutoReplyDetector.isAutoReply(message("Auto-Submitted", " Auto-Replied; owner-email=\"a@b.example\"")))
                .isTrue();
    }

    @Test
    void autoSubmittedNo_isNotAnAutoReply() throws Exception {
        assertThat(AutoReplyDetector.isAutoReply(message("Auto-Submitted", "no"))).isFalse();
    }

    @Test
    void autoGenerated_isNotEnough_evenOnAReply() throws Exception {
        // A customer's system sending a booking request: machine-written, but a real enquiry.
        assertThat(AutoReplyDetector.isAutoReply(message("Auto-Submitted", "auto-generated"))).isFalse();
        // A person answering through a helpdesk tool that stamps all its mail: must not be dropped.
        assertThat(AutoReplyDetector.isAutoReply(
                message("Auto-Submitted", "auto-generated", "In-Reply-To", "<quote-1@felixstowe.example.com>"))).isFalse();
    }

    @Test
    void replyHeadersAlone_areAnOrdinaryReply() throws Exception {
        assertThat(AutoReplyDetector.isAutoReply(message("In-Reply-To", "<quote-1@felixstowe.example.com>"))).isFalse();
    }

    @Test
    void legacyVacationHeaders_areAutoReplies() throws Exception {
        assertThat(AutoReplyDetector.isAutoReply(message("X-Autoreply", "yes"))).isTrue();
        assertThat(AutoReplyDetector.isAutoReply(message("X-Autoreply", "no"))).isFalse();
        assertThat(AutoReplyDetector.isAutoReply(message("X-Autorespond", "Out of office"))).isTrue();
        assertThat(AutoReplyDetector.isAutoReply(message("Precedence", "auto_reply"))).isTrue();
    }

    @Test
    void bulkPrecedence_isNotAnAutoReply() throws Exception {
        // Newsletters and mailing lists: junk or not is the classifier's call, not this rule's.
        assertThat(AutoReplyDetector.isAutoReply(message("Precedence", "bulk"))).isFalse();
    }
}
